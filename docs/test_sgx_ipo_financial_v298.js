"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs");
const {build,compare}=require("./sgx-ipo-financial-v298.js");
const read=p=>JSON.parse(fs.readFileSync(p,"utf8"));
const d=read("docs/data/sgx-ipo-audited-historical-v298.json");
const feed=read("docs/data/latest.json");
const values=build(d,feed);
assert.equal(values.length,2);
const deluge=values.find(x=>x.symbol==="9DC"),mim=values.find(x=>x.symbol==="MIM");
assert.ok(deluge&&mim);
assert.equal(deluge.currency,"SGD");
assert.equal(mim.currency,"USD");
assert.deepEqual(deluge.historical.map(x=>x.revenue),[113199,139755,116662]);
assert.deepEqual(deluge.historical.map(x=>x.profit),[11753,17896,11800]);
assert.deepEqual(deluge.historical.map(x=>x.equity),[23015,38320,49443]);
assert.deepEqual(mim.historical.map(x=>x.revenue),[39829,46821,65335]);
assert.deepEqual(mim.historical.map(x=>x.profit),[4112,8172,10008]);
assert.deepEqual(mim.historical.map(x=>x.equity),[87080,86088,95533]);
assert.deepEqual(deluge.historical.map(x=>x.equityRatio.toFixed(1)),["28.0","37.2","48.0"]);
assert.deepEqual(mim.historical.map(x=>x.equityRatio.toFixed(1)),["83.2","81.5","73.2"]);
assert.deepEqual(deluge.historical.map(x=>x.segmentOperatingResult),[17182,24506,17966]);
assert.equal(deluge.historical[0].segmentOperatingGrowth,null);
assert.equal(deluge.historical[2].segmentOperatingGrowth.toFixed(1),"-26.7");
assert.equal(deluge.historical[2].segmentOperatingMargin.toFixed(1),"15.4");
assert.ok(mim.historical.every(x=>x.segmentOperatingResult===null&&x.segmentOperatingMargin===null&&x.segmentOperatingGrowth===null));
assert.equal(mim.interim.equityRatio.toFixed(1),"70.6");
assert.ok(deluge.historical[2].revenueGrowth<-15 && deluge.historical[2].revenueGrowth>-18);
assert.ok(mim.historical[2].revenueGrowth>39 && mim.historical[2].revenueGrowth<41);
assert.ok(mim.interim.revenueYoY>109 && mim.interim.revenueYoY<110);
assert.equal(compare(100,200),100);
assert.equal(compare(0,200),null);
assert.equal(values.some(x=>x.rankEligible),false);
const reject=f=>{const clone=structuredClone(d),copy=structuredClone(feed);f(clone,copy);assert.throws(()=>build(clone,copy));};
reject(x=>{x.ranking_enabled=true});
reject(x=>{x.issuers[0].currency="USD"});
reject(x=>{x.issuers[0].periods[2].audit_status="UNAUDITED_PRO_FORMA"});
reject(x=>{x.issuers[0].periods[2].revenue=0});
reject(x=>{x.issuers[0].periods[2].total_assets=100});
reject(x=>{x.issuers[1].periods[2].segment_operating_result=10008});
reject(x=>{x.issuers[1].interim[0].total_assets=104630});
reject(x=>{x.issuers[0].rejected_lookalike_pro_forma.not_used_in_audited_growth=false});
reject(x=>{x.issuers[1].interim[0].period_end="2024-06-30"});
reject(x=>{x.issuers[1].interim[1].audit_status="AUDITED"});
reject(x=>{x.issuers[1].source_pdf_sha256="f".repeat(64)});
reject((x,f)=>{f.ranking_eligible_count=1});
const html=fs.readFileSync("docs/sgx-32-research.html","utf8");
assert.match(html,/sgx-ipo-financial-v298\.js/);
for(const id of ["sgxIpoFinancialStatus","sgxIpoFinancialRows"])assert.match(html,new RegExp('id="'+id+'"'));
assert.equal(feed.records.length,7);assert.equal(feed.ranking_eligible_count,0);
console.log("v298 PASS: audited 9DC 3-year / MIM 3-year plus unreviewed H1-year boundary, no pro forma/ranking contamination");
